const iso = (d: Date) => d.toISOString();

function checklist(prefix: string, items: [string, boolean][]): ChecklistItem[] {
  return items.map(([label, done], index) => ({
    id: `${prefix}-c${index + 1}`,
    label,
    done,
  }));
}

